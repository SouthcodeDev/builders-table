#!/usr/bin/env node
// build-marker-icons.mjs — lucide-react icon data → src/data/marker-icons.ts
//
//   node scripts/build-marker-icons.mjs
//
// Map markers are raw DOM (mapbox-gl takes an HTMLElement, not a React tree), so the
// icons cannot be <LucideIcon /> like everywhere else in the app. Rather than
// hand-copying path data — which goes stale the moment lucide is upgraded and nobody
// notices — this lifts the real path data out of node_modules and writes it as
// markup. Re-run it after bumping lucide-react.
//
// Refuses to write on a missing icon rather than emitting a blank marker.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const ICON_DIR = 'node_modules/lucide-react/dist/esm/icons'
const OUT = 'src/data/marker-icons.ts'

// Category (src/data/categories.ts) → lucide icon name. Keep the keys in sync with
// CATEGORY_KEYS; the typecheck in categories.ts will not catch a drift here, so the
// check at the bottom of this script does.
const ICONS = {
  'giving-back': 'hand-heart',
  pottery: 'palette',
  cooking: 'chef-hat',
  motorsport: 'car-front',
  cycling: 'bike',
  climbing: 'mountain-snow',
  water: 'waves',
  fashion: 'shirt',
  stage: 'drama',
  music: 'music',
  market: 'shopping-bag',
  running: 'footprints',
  hiking: 'mountain',
  coffee: 'coffee',
  food: 'utensils-crossed',
  art: 'palette',
  wellness: 'sparkles',
  heritage: 'landmark',
  fitness: 'dumbbell',
  beach: 'umbrella',
  nature: 'leaf',
  outdoors: 'trees',
  social: 'users',
  family: 'baby',
  place: 'map-pin',
}

const errors = []

/**
 * Pull the `node` array out of an icon module and re-emit it as SVG markup.
 * The modules are generated and uniform: `const __iconData = { ... node: [...] }`.
 */
function iconMarkup(name, seen = []) {
  const file = `${ICON_DIR}/${name}.mjs`
  if (!existsSync(file)) {
    errors.push(`icon "${name}" not found at ${file}`)
    return ''
  }
  const src = readFileSync(file, 'utf8')

  // Some names are aliases that re-export the real icon ("waves" → "waves-horizontal").
  const alias = src.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/)
  if (alias) {
    if (seen.includes(name)) {
      errors.push(`icon "${name}": circular alias chain ${[...seen, name].join(' → ')}`)
      return ''
    }
    return iconMarkup(alias[1], [...seen, name])
  }

  const start = src.indexOf('node: [')
  if (start === -1) {
    errors.push(`icon "${name}": no node array — lucide's output format changed`)
    return ''
  }
  // Walk the brackets so a nested array inside an attribute can't end the match early.
  let depth = 0
  let end = -1
  for (let i = src.indexOf('[', start); i < src.length; i++) {
    if (src[i] === '[') depth++
    else if (src[i] === ']' && --depth === 0) { end = i + 1; break }
  }
  if (end === -1) {
    errors.push(`icon "${name}": unbalanced node array`)
    return ''
  }

  // The array is JS, not JSON: unquoted keys and trailing-comma-free. Evaluating
  // node_modules source we just read is no more trust than importing it would be.
  let node
  try {
    node = new Function(`return ${src.slice(start + 'node: '.length, end)}`)()
  } catch (e) {
    errors.push(`icon "${name}": could not parse node array — ${e.message}`)
    return ''
  }

  return node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        // `key` is React bookkeeping and is not a valid SVG attribute.
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`)
        .join(' ')
      return `<${tag} ${a}/>`
    })
    .join('')
}

const entries = Object.entries(ICONS).map(([category, icon]) => [category, iconMarkup(icon)])

// A category whose markup came back empty would render as an invisible marker.
entries.forEach(([category, markup]) => {
  if (!markup) errors.push(`category "${category}" produced no markup`)
})

// Guard the hand-maintained key list against categories.ts drifting away from it.
const declared = readFileSync('src/data/categories.ts', 'utf8')
const listed = [...declared.matchAll(/'([a-z-]+)',?/g)]
  .map((m) => m[1])
  .filter((k) => declared.slice(declared.indexOf('CATEGORY_KEYS'), declared.indexOf('] as const')).includes(`'${k}'`))
const missing = [...new Set(listed)].filter((k) => !(k in ICONS))
if (missing.length) errors.push(`categories with no icon mapping: ${missing.join(', ')}`)

if (errors.length) {
  console.error('✗ nothing written:\n' + errors.map((e) => '  · ' + e).join('\n'))
  process.exit(1)
}

const version = JSON.parse(readFileSync('node_modules/lucide-react/package.json', 'utf8')).version

const out = `// GENERATED by scripts/build-marker-icons.mjs — do not hand-edit.
// Source: lucide-react ${version} · ${entries.length} categories
//
// Map markers are raw DOM, so their icons cannot be React components like the rest
// of the app's. This is the same lucide art, lifted to markup. Re-run the script
// after upgrading lucide-react.

import type { Category } from './categories'

/** Inner markup for a 24x24 lucide viewBox. Wrap it in your own <svg>. */
export const MARKER_ICONS: Record<Category, string> = ${JSON.stringify(
  Object.fromEntries(entries),
  null,
  2,
)}
`

writeFileSync(OUT, out)
console.log(`✓ ${entries.length} marker icons → ${OUT} (lucide-react ${version})`)
